// Generate version metadata once, then bind every native verifier and publisher
// to that exact recipe and payload. These functions never commit or publish.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import * as fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { generatedFiles, planVersionUpdate, prepareReleaseVersion, requireNewVersion } from './prepare-release-version.mjs'

const contract = 'physicalsystems-generated-release-v1'
const root = fileURLToPath(new URL('../', import.meta.url))
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex')
const json = (value) => `${JSON.stringify(value, null, 2)}\n`
const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', timeout: 30_000, stdio: 'pipe' }).trim()
const run = (cwd, script, args = []) => execFileSync(process.execPath, [script, ...args], { cwd, stdio: 'pipe', timeout: 60_000 })

async function outside(sourceRoot, directory) {
  assert.ok(path.isAbsolute(directory), 'Input artifacts require an absolute directory')
  const parent = await fs.realpath(path.dirname(directory))
  let resolved = path.join(parent, path.basename(directory))
  try { resolved = await fs.realpath(directory) } catch (error) { if (error.code !== 'ENOENT') throw error }
  const relative = path.relative(await fs.realpath(sourceRoot), resolved)
  assert.ok(path.isAbsolute(relative) || relative.split(path.sep)[0] === '..', 'Input artifacts must stay outside source')
}

export async function generateReleaseInputs(sourceRoot, plan, directory) {
  assert.equal(plan.action, 'publish')
  assert.equal(git(sourceRoot, 'rev-parse', 'HEAD'), plan.base, 'Source changed after planning')
  assert.match(plan.base, /^[a-f0-9]{40}$/)
  requireNewVersion(plan.published, plan.version)
  await outside(sourceRoot, directory)
  await fs.mkdir(directory, { recursive: true })
  const release = JSON.parse(await fs.readFile(path.join(sourceRoot, 'release/product.json')))
  const record = { contractVersion: contract, sourceCommit: plan.base, sourceVersion: release.product.version,
    version: plan.version, previousPreview: plan.published }
  const options = { previousPreview: plan.published, candidateRecord: record }
  const recipe = await planVersionUpdate(sourceRoot, plan.version, options)
  await prepareReleaseVersion(sourceRoot, plan.version, { ...options, print() {} })
  try {
    const files = {}
    for (const file of recipe.originals.keys()) files[file] = await fs.readFile(path.join(sourceRoot, file), 'utf8')
    const bytes = json({ ...record, files })
    await fs.writeFile(path.join(directory, 'release-inputs.json'), bytes, { flag: 'wx' })
    await fs.writeFile(path.join(directory, 'release-inputs.sha256'), `${hash(bytes)}  release-inputs.json\n`, { flag: 'wx' })
    return hash(bytes)
  } finally {
    // The preparation job keeps its exact main checkout. Only downstream CI
    // workspaces receive the generated inputs; no branch or commit is created.
    for (const [file, value] of recipe.originals) await fs.writeFile(path.join(sourceRoot, file), value)
  }
}

export async function restoreReleaseInputs(sourceRoot, filename, expectedHash, expectedVersion) {
  assert.match(expectedHash || '', /^[a-f0-9]{64}$/)
  assert.equal(git(sourceRoot, 'status', '--porcelain'), '', 'Generated inputs require a clean source checkout')
  const stat = await fs.lstat(filename)
  assert.ok(!stat.isSymbolicLink() && stat.size > 0 && stat.size <= 8 * 1024 * 1024, 'Invalid generated input artifact')
  const bytes = await fs.readFile(filename)
  assert.equal(hash(bytes), expectedHash, 'Generated input digest differs from the preparation job')
  const bundle = JSON.parse(bytes)
  assert.deepEqual(Object.keys(bundle).sort(), ['contractVersion', 'files', 'previousPreview', 'sourceCommit', 'sourceVersion', 'version'])
  const { files, ...record } = bundle
  assert.equal(record.contractVersion, contract)
  assert.equal(record.sourceCommit, git(sourceRoot, 'rev-parse', 'HEAD'), 'Generated input source commit mismatch')
  assert.equal(record.version, expectedVersion, 'Generated input version mismatch')
  const release = JSON.parse(await fs.readFile(path.join(sourceRoot, 'release/product.json')))
  assert.equal(record.sourceVersion, release.product.version)
  requireNewVersion(record.previousPreview, record.version)
  const recipe = await planVersionUpdate(sourceRoot, record.version, { previousPreview: record.previousPreview, candidateRecord: record })
  assert.deepEqual(Object.keys(files).sort(), [...recipe.originals.keys()].sort(), 'Unexpected generated input paths')
  // Even a digest-matching artifact may not inject arbitrary source: every
  // non-generated byte must match the reviewed version-generation recipe.
  for (const [file, before] of recipe.originals) {
    assert.equal(typeof files[file], 'string')
    if (!generatedFiles.includes(file)) assert.equal(files[file], recipe.updates.get(file) ?? before, `Generated input differs from version recipe: ${file}`)
  }
  try {
    for (const [file, value] of Object.entries(files)) await fs.writeFile(path.join(sourceRoot, file), value)
    run(sourceRoot, 'scripts/legal/sbom.mjs', ['--check'])
    run(sourceRoot, 'scripts/check-export-boundary.mjs')
    run(sourceRoot, 'scripts/release.mjs', ['check'])
  } catch (error) {
    for (const [file, value] of recipe.originals) await fs.writeFile(path.join(sourceRoot, file), value)
    throw new Error(`Generated input verification failed; original source restored. ${error.stderr?.toString() || error.message}`, { cause: error })
  }
  return record
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const record = await restoreReleaseInputs(root, path.join(process.env.RUNNER_TEMP, 'release-inputs', 'release-inputs.json'),
      process.env.RELEASE_INPUTS_SHA256, process.env.RELEASE_VERSION)
    console.log(`Verified generated ${record.version} inputs from source ${record.sourceCommit}`)
  } catch (error) { console.error(error.message); process.exitCode = 1 }
}
